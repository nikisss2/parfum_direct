export function resolveNotesForProduct(brand: string, name: string): PerfumeNotes | null {
  const b = brand.toLowerCase();
  const n = name.toLowerCase();
  for (const rule of NOTE_RULES) {
    if (rule.match(b, n)) {
      return rule.notes;
    }
  }
  return null;
}
