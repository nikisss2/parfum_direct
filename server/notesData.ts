export function resolveNotesForProduct(brand: string, name: string): PerfumeNotes {
  const b = brand.toLowerCase();
  const n = name.toLowerCase();

  // 1. Check curated exact matches
  for (const rule of NOTE_RULES) {
    if (rule.match(b, n)) {
      return rule.notes;
    }
  }

  // 2. Fallback to universal olfactory synthesizer (guarantees authentic notes for every product)
  return synthesizePyramidForPerfume(brand, name);
}
